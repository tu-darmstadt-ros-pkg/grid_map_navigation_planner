grid_map::GridMap loadMap(const YAML::Node& config)
{
  const auto filename = config["map"].as<std::string>();
  const auto metadata = YAML::LoadFile(filename);
  auto image_path = metadata["image"].as<std::string>();
  if (image_path.front() != '/')
    image_path = filename.substr(0, filename.find_last_of('/') + 1) + image_path;
  const auto image = cv::imread(image_path, cv::IMREAD_GRAYSCALE);
  if (image.empty()) throw std::runtime_error("Cannot read map image: " + image_path);
  nav_msgs::OccupancyGrid occupancy;
  occupancy.header.frame_id = "map";
  occupancy.info.resolution = metadata["resolution"].as<double>();
  occupancy.info.width = image.cols;
  occupancy.info.height = image.rows;
  occupancy.info.origin.position.x = metadata["origin"][0].as<double>();
  occupancy.info.origin.position.y = metadata["origin"][1].as<double>();
  if (metadata["origin"][2].as<double>() != 0.0)
    throw std::runtime_error("Fixture loader requires zero map yaw");
  occupancy.info.origin.orientation.w = 1.0;
  const bool negate = metadata["negate"].as<int>() != 0;
  const double occupied_threshold = metadata["occupied_thresh"].as<double>();
  const double free_threshold = metadata["free_thresh"].as<double>();
  occupancy.data.reserve(image.total());
  for (int y = image.rows - 1; y >= 0; --y) {
    for (int x = 0; x < image.cols; ++x) {
      double probability = image.at<unsigned char>(y, x) / 255.0;
      if (!negate) probability = 1.0 - probability;
      occupancy.data.push_back(probability > occupied_threshold ? 100 :
                               probability < free_threshold ? 0 : -1);
    }
  }
  grid_map::GridMap map;
  if (!grid_map::GridMapRosConverter::fromOccupancyGrid(occupancy, "occupancy", map))
    throw std::runtime_error("Cannot convert fixture occupancy grid");
  // Match the cloud loader: apply GO first, then NO_GO, at cell centres.
  const auto zones = YAML::LoadFile(config["zones"].as<std::string>())["zones"];
  for (const std::string type : {"GO", "NO_GO"}) {
    for (const auto& zone : zones) {
      if (zone["type"].as<std::string>() != type) continue;
      grid_map::Polygon polygon;
      for (const auto& point : zone["points"])
        polygon.addVertex({point["x"].as<double>(), point["y"].as<double>()});
      for (grid_map::PolygonIterator it(map, polygon); !it.isPastEnd(); ++it)
        map.at("occupancy", *it) = type == "GO" ? 0.0f : 100.0f;
    }
  }
  return map;
}

geometry_msgs::Pose pose(const YAML::Node& point)
{
  geometry_msgs::Pose result;
  result.position.x = point[0].as<double>();
  result.position.y = point[1].as<double>();
  result.orientation.w = 1.0;
  return result;
}

size_t blockedCells(const grid_map::GridMap& map, const std::vector<geometry_msgs::PoseStamped>& path)
{
  size_t blocked = 0;
  for (size_t i = 1; i < path.size(); ++i) {
    grid_map::Index from, to;
    if (!map.getIndex({path[i-1].pose.position.x, path[i-1].pose.position.y}, from) ||
        !map.getIndex({path[i].pose.position.x, path[i].pose.position.y}, to))
      throw std::runtime_error("Path leaves fixture map");
    for (grid_map::LineIterator it(map, from, to); !it.isPastEnd(); ++it)
      if (map.at("occupancy", *it) != 0.0f) ++blocked;
  }
  return blocked;
}

// Opt-in because the customer-supplied map and request coordinates are private.
// Enable explicitly with --gtest_also_run_disabled_tests and the configuration
// generated by prepare_straight_line_example.py. Missing inputs must fail.
TEST(StraightLineExample, DISABLED_FailedRequestsPreserveRoutedPaths)
{
  const char* config_path = std::getenv("GRID_MAP_PLANNER_REPRO_CONFIG");
  ASSERT_NE(config_path, nullptr) << "Set GRID_MAP_PLANNER_REPRO_CONFIG; see test/README.md";
  const auto config = YAML::LoadFile(config_path);
  const auto map = loadMap(config);
  grid_map_planner::GridMapPlanner fresh, reused;
  ASSERT_TRUE(fresh.setMap(map));
  ASSERT_TRUE(reused.setMap(map));
  const auto routes = config["routes"];
  ASSERT_EQ(routes.size(), 2u);
  std::vector<std::vector<geometry_msgs::PoseStamped>> expected(routes.size());
  for (size_t i = 0; i < routes.size(); ++i) {
    ASSERT_TRUE(fresh.makePlan(pose(routes[i][0]), pose(routes[i][1]), expected[i]));
    ASSERT_GT(expected[i].size(), 3u);
    ASSERT_EQ(blockedCells(map, expected[i]), 0u);
    std::cout << "Fresh route " << i << ": " << expected[i].size() << " poses, no blocked cells\n";
  }
  const auto triggers = config["triggers"];
  ASSERT_EQ(triggers.size(), 2u);
  std::vector<geometry_msgs::PoseStamped> failed;
  ASSERT_FALSE(reused.makePlan(pose(triggers[0][0]), pose(triggers[0][1]), failed));
  const auto good_distances = reused.getPlanningMap()["distance_transform"];
  ASSERT_FALSE(reused.makePlan(pose(triggers[1][0]), pose(triggers[1][1]), failed));
  EXPECT_TRUE((good_distances.array() == reused.getPlanningMap()["distance_transform"].array()).all());
  for (size_t i = 0; i < routes.size(); ++i) {
    std::vector<geometry_msgs::PoseStamped> actual;
    ASSERT_TRUE(reused.makePlan(pose(routes[i][0]), pose(routes[i][1]), actual));
    const auto blocked = blockedCells(map, actual);
    std::cout << "Reused route " << i << ": " << actual.size() << " poses, " << blocked << " blocked cells\n";
    EXPECT_EQ(blocked, 0u);
    EXPECT_GT(actual.size(), 3u);
    EXPECT_EQ(actual.size(), expected[i].size());
    if (actual.size() == expected[i].size()) {
      for (size_t j = 0; j < actual.size(); ++j) {
        EXPECT_DOUBLE_EQ(actual[j].pose.position.x, expected[i][j].pose.position.x);
        EXPECT_DOUBLE_EQ(actual[j].pose.position.y, expected[i][j].pose.position.y);
      }
    }
  }
}
